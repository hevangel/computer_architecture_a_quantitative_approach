"""Generate identical SystemVerilog and VHDL cycle vectors from the Python model."""
from pathlib import Path
import sys
from cycle_reference import generate

root=Path(__file__).resolve().parent.parent
trace,model=generate()
fields=[('valid',1),('write',1),('addr',8),('data',32),('ident',6),('allow',1),
        ('ready',1),('hv',1),('hid',6),('hd',32),('fv',1),('fid',6),('fd',32),
        ('mv',1),('mw',1),('ma',8),('mt',2),('hit_count',8),('pri_count',8),('sec_count',8),('wb_count',8)]
width=sum(w for _,w in fields)
def encode(frame):
    req,allow,(ready,hit,fill,mem,counts)=frame
    write,addr,data,ident=req or (0,0,0,0)
    hid,hd=hit or (0,0); fid,fd=fill or (0,0); mw,ma,mt=mem or (0,0,0)
    vals=[bool(req),write,addr,data,ident,allow,ready,bool(hit),hid,hd,bool(fill),fid,fd,bool(mem),mw,ma,mt,*counts]
    return ''.join(format(int(x),f'0{w}b') for x,(_,w) in zip(vals,fields))
bits=[encode(f) for f in trace]
assert all(len(x)==width for x in bits)
sv=f'''// Generated by python/generate_trace.py; do not hand-edit.
package nb_reference_pkg;
 localparam integer TRACE_WIDTH={width}, TRACE_LENGTH={len(trace)};
 function automatic [TRACE_WIDTH-1:0] reference_frame(input integer n);
  case(n)
'''+''.join(f"   {i}: reference_frame={width}'b{b};\n" for i,b in enumerate(bits))+'''   default: reference_frame='0;
  endcase
 endfunction
endpackage
'''
vhd=f'''-- Generated by python/generate_trace.py; do not hand-edit.
library ieee; use ieee.std_logic_1164.all;
package nb_reference_pkg is
 constant TRACE_WIDTH:natural:={width}; constant TRACE_LENGTH:natural:={len(trace)};
 function reference_frame(n:natural) return std_logic_vector;
end package;
package body nb_reference_pkg is
 function reference_frame(n:natural) return std_logic_vector is
 begin
  case n is
'''+''.join(f'   when {i} => return "{b}";\n' for i,b in enumerate(bits))+'''   when others => return (TRACE_WIDTH-1 downto 0 => '0');
  end case;
 end function;
end package body;
'''
outputs=((root/'sv/nb_reference_pkg.sv',sv),(root/'vhdl/nb_reference_pkg.vhd',vhd))
for path,content in outputs:
    if '--check' in sys.argv:
        if path.read_text()!=content: raise SystemExit(f'stale reference vectors: {path}')
    else:
        path.write_text(content)
print(f'{len(trace)} cycles, {width} bits per frame, peak {model.peak_misses} MSHRs, {model.forwarded} buffered forwards')
